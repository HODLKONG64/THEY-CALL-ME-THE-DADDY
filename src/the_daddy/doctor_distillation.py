VERSION = 2
BATCH = 5
MAX_CONTEXT_BYTES = 7200
MAX_RECORD_BYTES = 1900
TECH = re.compile(r"\b(?:bug|fix(?:ed|es)?|fail(?:ed|ure|ing)?|regression|timeout|error|crash|broken|deploy(?:ment|ed)?|migration|security|validation|verify|test(?:s|ing)?|worker|webhook|api|database|cache|latency|permission|authentication|authorization|rollback|retry|race|deadlock|memory|sync|workflow|404|403|500|503|d1|r2|ci)\b", re.I)
ART = re.compile(r"\b(?:artwork|sprite(?:s|sheet)?|wallpaper|illustration|graffiti|poster|portrait|banner|icon|logo|texture|art asset)\b", re.I)
NOISE = re.compile(r"^(?:@codex\s+(?:review|security review|address)|(?:thanks|thank you|done|merged|lgtm|looks good|approved|great work|please review)[.! ]*$|(?:useful\?|about codex|review trigger|codex review summary|generated by|automatically generated|signed-off-by:|co-authored-by:)|(?:#{1,6}\s*)?(?:summary|description|changes|checklist|test plan|screenshots|review|testing)\s*:?\s*$)", re.I)
MARKUP = re.compile(r"<!--[\s\S]*?-->|</?(?:details|summary)\b[^>]*>|!\[[^\]]*\]\([^)]*\)|https?://\S+", re.I)
SECTION = re.compile(r"^\s*(?:#{1,6}\s+)?(?:\*\*)?(root cause|cause|problem|symptoms?|fix|solution|resolution|verification|validation|test(?:ing|s)?|failure|rollback)(?:\*\*)?\s*:\s*(.*)$", re.I)
SECRET_PATH = re.compile(r"(^|/)(?:\.env(?:\.|$)|secrets?(?:/|\.|$)|credentials?(?:/|\.|$))", re.I)


def compact_lines(value, settings, *, limit=8, technical=False):
    clean = scrub(MARKUP.sub(" ", str(value or "")[:16000]), settings)
    seen = set()
    lines = []
    for line in clean.splitlines():
        line = re.sub(r"^\s*(?:[-*+]|\d+\.)\s+(?:\[[ xX]\]\s*)?", "", line).strip()
        line = re.sub(r"\s+", " ", line)
        if not line or NOISE.match(line) or re.fullmatch(r"[\s|:_#*\x60-]+", line):
            continue
        if technical and not TECH.search(line):
            continue
        key = line.casefold().strip(".!")
        if key in seen:
            continue
        seen.add(key)
        lines.append(line[:320])
        if len(lines) >= limit:
            break
    return lines


def revision(row):
    return hashlib.sha256(json.dumps([VERSION, *row], ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def metadata(row, settings):
    repo, number, kind, state, updated, title, body = row
    title = " ".join(compact_lines(title, settings, limit=1))[:180]
    clean = compact_lines(body, settings, limit=24)
    combined = title + "\n" + "\n".join(clean)
    classification = "technical" if TECH.search(combined) else ("art_only_candidate" if ART.search(combined) else "uncertain")
    fields = {"reported_problem": [], "reported_root_cause": [], "reported_solution": [],
              "reported_verification": [], "reported_failure": []}
    groups = {"root cause": "reported_root_cause", "cause": "reported_root_cause",
              "problem": "reported_problem", "symptom": "reported_problem", "symptoms": "reported_problem",
              "fix": "reported_solution", "solution": "reported_solution", "resolution": "reported_solution",
              "verification": "reported_verification", "validation": "reported_verification",
              "test": "reported_verification", "tests": "reported_verification", "testing": "reported_verification",
              "failure": "reported_failure", "rollback": "reported_failure"}
    for line in clean:
        match = SECTION.match(line)
        if match and match[2]:
            fields[groups[match[1].lower()]].append(match[2][:250])
    return {"repo": repo, "number": number, "kind": kind, "source_updated": updated,
            "source_revision": revision(row), "distillation_version": VERSION,
            "classification": classification, "title": title,
            "status": "open_unverified" if state != "closed" else "closed_unverified",
            "url": f"https://github.com/{repo}/{'pull' if kind == 'pr' else 'issues'}/{number}",
            **{k: list(dict.fromkeys(v))[:2] for k, v in fields.items() if v},
            "technical_notes": compact_lines(body, settings, technical=True, limit=3)}


def connect(index):
    db = index.connect()
    with db:
        db.execute("""CREATE TABLE IF NOT EXISTS distilled_history (
            repo TEXT NOT NULL, number INTEGER NOT NULL, revision TEXT NOT NULL,
            version INTEGER NOT NULL, processed TEXT NOT NULL, retry_after TEXT NOT NULL,
            complete INTEGER NOT NULL, record TEXT NOT NULL, source_bytes INTEGER NOT NULL,
            PRIMARY KEY(repo,number)
        )""")
        db.execute("""CREATE TABLE IF NOT EXISTS distillation_backoff (
            repo TEXT NOT NULL, family TEXT NOT NULL, retry_after TEXT NOT NULL,
            reason TEXT NOT NULL, PRIMARY KEY(repo,family)
        )""")
    return db


def checked_list(value):
    if not isinstance(value, list) or not all(isinstance(item, dict) for item in value):
        raise ValueError("Incomplete historical evidence response")
    return value


def error_reason(exc):
    """Do not log response bodies, request headers or arbitrary exception text."""
    cause = exc
    while cause is not None:
        if isinstance(cause, HTTPError):
            status = cause.code
            if status == 429 or (status == 403 and (
                    (cause.headers or {}).get("X-RateLimit-Remaining") == "0"
                    or (cause.headers or {}).get("Retry-After"))):
                return "rate_limited", status
            if status in (401, 403):
                return "permission_or_authentication_denied", status
            if status == 404:
                return "not_found_or_inaccessible", status
            return "http_error", status
        cause = cause.__cause__
    return ("invalid_response" if isinstance(exc, (ValueError, TypeError, AttributeError))
            else "transport_or_api_error"), None


class EvidenceReader:
    """Keep per-repository capability cooldowns outside the repair execution path."""
    def __init__(self, db, repo, api, now):
        self.db, self.repo, self.api, self.now = db, repo, api, now
        self.diagnostics = []
        self.failures = 0
        self.deferred = 0
        self.suspended = False
        self.retry_until = now

    def fetch(self, family, endpoint, validate, unavailable):
        stamp = self.now.isoformat(timespec="seconds")
        cooldown = self.db.execute(
            "SELECT retry_after,reason FROM distillation_backoff WHERE repo=? AND family=?",
            (self.repo, family)).fetchone()
        global_cooldown = self.db.execute(
            "SELECT retry_after,reason FROM distillation_backoff WHERE repo=? AND family=?",
            ("*", "rate_limit")).fetchone()
        if global_cooldown and global_cooldown[0] > stamp:
            cooldown = global_cooldown
        if self.suspended or (cooldown and cooldown[0] > stamp):
            if cooldown and cooldown[0] > stamp:
                self.retry_until = max(self.retry_until, datetime.fromisoformat(cooldown[0]))
            unavailable[family] = "unknown_deferred"
            self.deferred += 1
            return None
        try:
            value = validate(self.api(self.repo, endpoint))
        except (RuntimeError, OSError, ValueError, TypeError, AttributeError) as exc:
            reason, status = error_reason(exc)
            self.failures += 1
            unavailable[family] = "unknown_" + reason
            self.diagnostics.append({"endpoint": f"GET /repos/{self.repo}/{endpoint}",
                                     "http_status": status, "error": reason})
            # 404 can be object-specific: never suppress an entire capability on it.
            if reason in ("permission_or_authentication_denied", "rate_limited"):
                retry = self.now + timedelta(hours=24 if reason.startswith("permission") else 1)
                self.retry_until = max(self.retry_until, retry)
                key = ("*", "rate_limit") if reason == "rate_limited" else (self.repo, family)
                with self.db:
                    self.db.execute("INSERT OR REPLACE INTO distillation_backoff VALUES(?,?,?,?)",
                                    (*key, retry.isoformat(timespec="seconds"), reason))
            if reason == "rate_limited":
                self.suspended = True
            if status == 404:
                # Retry this record less often without suppressing other objects.
                self.retry_until = max(self.retry_until, self.now + timedelta(hours=24))
            return None
        with self.db:
            self.db.execute("DELETE FROM distillation_backoff WHERE repo=? AND family=? AND retry_after<=?",
                            (self.repo, family, stamp))
        return value


def checked_pr(detail):
    if not isinstance(detail, dict) or type(detail.get("merged")) is not bool:
        raise ValueError("Missing PR merge evidence")
    return detail


def checked_checks(checks):
    if not isinstance(checks, dict):
        raise ValueError("Missing historical check response")
    return checked_list(checks.get("check_runs"))


def checked_runs(value):
    if not isinstance(value, dict):
        raise ValueError("Missing workflow runs response")
    return checked_list(value.get("workflow_runs"))


def checked_jobs(value):
    if not isinstance(value, dict):
        raise ValueError("Missing workflow jobs response")
    return checked_list(value.get("jobs"))


def observed_state(status, conclusion):
    if status != "completed":
        return "pending" if status in ("queued", "in_progress", "waiting", "requested", "pending") else "unknown"
    if conclusion == "success":
        return "passed"
    if conclusion in ("failure", "timed_out", "startup_failure", "action_required"):
        return "failed"
    return "unknown"


def alternative_ci(record, reader, settings, unavailable, previous):
    """Bounded exact-SHA observations, never a substitute for required merge checks."""
    sha = record["merge_sha"]
    evidence = {}
    prior = previous.get("alternative_ci", {}) if previous.get("merge_sha") == sha else {}
    runs = prior.get("workflow_runs")
    if not runs or any(item.get("state") in ("pending", "unknown") or item.get("jobs_unavailable")
                       or any(job.get("state") in ("pending", "unknown") for job in item.get("jobs", []))
                       for item in runs):
        rows = reader.fetch("workflow_runs", f"actions/runs?head_sha={sha}&per_page=20",
                            checked_runs, unavailable)
        if rows is not None:
            runs = []
            for run in rows[:20]:
                if run.get("head_sha") != sha or run.get("event") not in ("push", "workflow_dispatch"):
                    continue
                run_id, attempt = run.get("id"), run.get("run_attempt")
                if type(run_id) is not int or run_id < 1 or type(attempt) is not int or attempt < 1:
                    continue
                item = {"id": run_id, "attempt": attempt,
                        "name": scrub(str(run.get("name") or ""), settings)[:100],
                        "state": observed_state(run.get("status"), run.get("conclusion"))}
                jobs = reader.fetch("workflow_jobs", f"actions/runs/{run_id}/attempts/{attempt}/jobs?per_page=20",
                                    checked_jobs, unavailable)
                if jobs is None:
                    item["jobs_unavailable"] = True
                else:
                    item["jobs"] = [{"name": scrub(str(job.get("name") or ""), settings)[:100],
                                     "state": observed_state(job.get("status"), job.get("conclusion"))}
                                    for job in jobs[:20] if job.get("head_sha") == sha][:4]
                runs.append(item)
                if len(runs) >= 3:
                    break
    if runs is not None:
        evidence["workflow_runs"] = runs
    statuses = prior.get("commit_statuses")
    if not statuses or any(item.get("state") in ("pending", "unknown") for item in statuses):
        rows = reader.fetch("commit_statuses", f"commits/{sha}/statuses?per_page=30",
                            checked_list, unavailable)
        if rows is not None:
            statuses = []
            seen = set()
            for row in rows[:30]:
                context = scrub(str(row.get("context") or ""), settings)[:100]
                if not context or context in seen:
                    continue
                seen.add(context)
                state = {"success": "passed", "failure": "failed", "error": "failed",
                         "pending": "pending"}.get(str(row.get("state")), "unknown")
                statuses.append({"context": context, "state": state})
                if len(statuses) >= 6:
                    break
    if statuses is not None:
        evidence["commit_statuses"] = statuses
    record["alternative_ci"] = evidence
    record["ci_evidence_source"] = "alternative_bounded_sample"


def enrich(record, reader, settings, previous=None):
    number, kind = record["number"], record["kind"]
    unavailable = {}
    previous = previous or {}
    missing = previous.get("unavailable_evidence", {})
    reuse = bool(previous) and isinstance(missing, dict)
    if record["classification"] != "technical":
        return unavailable
    if kind == "pr":
        cached_status = previous.get("status")
        cached_merge = previous.get("merge_sha")
        reusable_detail = cached_status == "closed_unmerged" or (
            cached_status == "merged_not_production_verified"
            and isinstance(cached_merge, str) and SHA.fullmatch(cached_merge))
        if reuse and "pr_detail" not in missing and reusable_detail:
            detail = {"merged": previous["status"] == "merged_not_production_verified",
                      "merge_commit_sha": previous.get("merge_sha"), "head": {"sha": previous.get("head_sha")}}
        else:
            detail = reader.fetch("pr_detail", f"pulls/{number}", checked_pr, unavailable)
        if detail is not None and detail["merged"]:
            record["status"] = "merged_not_production_verified"
            for name, value in (("merge_sha", detail.get("merge_commit_sha")),
                                ("head_sha", (detail.get("head") or {}).get("sha")
                                 if isinstance(detail.get("head"), dict) else None)):
                if isinstance(value, str) and SHA.fullmatch(value):
                    record[name] = value
            same_merge = reuse and record.get("merge_sha") == previous.get("merge_sha") and record.get("head_sha") == previous.get("head_sha")
            if same_merge and "affected_paths" in previous and "pr_files" not in missing:
                record["affected_paths"] = previous["affected_paths"]
                files = None
            else:
                files = reader.fetch("pr_files", f"pulls/{number}/files?per_page=20", checked_list, unavailable)
            if files is not None:
                paths = []
                for item in files[:20]:
                    path = str(item.get("filename") or "")
                    if path and not SECRET_PATH.search(path):
                        paths.append(scrub(path, settings)[:150])
                record["affected_paths"] = list(dict.fromkeys(paths))[:8]
            if same_merge and "review_findings_unverified" in previous and "pr_comments" not in missing:
                record["review_findings_unverified"] = previous["review_findings_unverified"]
                inline = None
            else:
                inline = reader.fetch("pr_comments", f"pulls/{number}/comments?per_page=20", checked_list, unavailable)
            if inline is not None:
                notes = []
                for item in inline[:20]:
                    notes.extend(compact_lines(item.get("body"), settings, technical=True, limit=2))
                record["review_findings_unverified"] = list(dict.fromkeys(notes))[:3]
            if "merge_sha" in record:
                if same_merge and "observed_merge_checks" in previous and "merge_checks" not in missing:
                    record["observed_merge_checks"] = previous["observed_merge_checks"]
                    check_rows = None
                else:
                    check_rows = reader.fetch("merge_checks", f"commits/{record['merge_sha']}/check-runs?per_page=30",
                                              checked_checks, unavailable)
                if check_rows is not None:
                    record["observed_merge_checks"] = [
                        {"name": scrub(str(item.get("name") or ""), settings)[:100],
                         "conclusion": scrub(str(item.get("conclusion") or "pending"), settings)[:30]}
                        for item in check_rows[:30] if item.get("head_sha") == record["merge_sha"]
                    ][:6]
                if "merge_checks" in unavailable:
                    alternative_ci(record, reader, settings, unavailable, previous if same_merge else {})
            else:
                unavailable["merge_checks"] = "unknown_missing_merge_sha"
        elif detail is not None and record["status"] == "closed_unverified":
            record["status"] = "closed_unmerged"
    if reuse and "discussion_notes_unverified" in previous and "issue_comments" not in missing:
        record["discussion_notes_unverified"] = previous["discussion_notes_unverified"]
        comments = None
    else:
        comments = reader.fetch("issue_comments", f"issues/{number}/comments?per_page=20", checked_list, unavailable)
    if comments is not None:
        notes = []
        for item in comments[:20]:
            notes.extend(compact_lines(item.get("body"), settings, technical=True, limit=2))
        record["discussion_notes_unverified"] = list(dict.fromkeys(notes))[:3]
    return unavailable


def distill_pending(index, repo, api, *, limit=BATCH):
    now = datetime.now(timezone.utc)
    stamp = now.isoformat(timespec="seconds")
    db = connect(index)
    processed = skipped = errors = partial = 0
    reader = EvidenceReader(db, repo, api, now)
    try:
        rows = db.execute("""SELECT h.repo,h.number,h.kind,h.state,h.updated,h.title,h.body,
                                    d.revision,d.version,d.processed,d.retry_after,d.complete,d.record
                             FROM history h LEFT JOIN distilled_history d
                               ON h.repo=d.repo AND h.number=d.number WHERE h.repo=?
                             ORDER BY CASE WHEN d.number IS NULL THEN 0 ELSE 1 END,
                                      d.processed ASC, h.number ASC""", (repo,)).fetchall()
        for row in rows:
            if processed >= limit:
                break
            raw = row[:7]
            old_revision, version, when, retry, complete, cached_record = row[7:]
            rev = revision(raw)
            if old_revision == rev and version == VERSION:
                if retry and retry > stamp:
                    continue
                if complete and when > (now - timedelta(days=30)).isoformat(timespec="seconds"):
                    skipped += 1
                    continue
            record = metadata(raw, index.settings)
            previous = None
            if old_revision == rev and version == VERSION and not complete and cached_record:
                candidate = json.loads(cached_record)
                started = candidate.get("evidence_started_at", "")
                if started > (now - timedelta(days=30)).isoformat(timespec="seconds"):
                    previous = candidate
            record["evidence_started_at"] = previous["evidence_started_at"] if previous else stamp
            reader.retry_until = now
            unavailable = enrich(record, reader, index.settings, previous)
            successful = not unavailable
            if unavailable:
                partial += 1
                errors += 1
                record["unavailable_evidence"] = unavailable
            record["evidence_complete_for_bounded_sample"] = successful and record["classification"] == "technical"
            retry_at = "" if successful else max(reader.retry_until, now + timedelta(hours=1)).isoformat(timespec="seconds")
            payload = json.dumps(record, ensure_ascii=False, separators=(",", ":"))
            # Recheck source revision before committing a result computed outside the transaction.
            with db:
                db.execute("BEGIN IMMEDIATE")
                current = db.execute("SELECT repo,number,kind,state,updated,title,body FROM history WHERE repo=? AND number=?",
                                     (repo, raw[1])).fetchone()
                if current is not None and revision(current) == rev:
                    db.execute("""INSERT INTO distilled_history VALUES(?,?,?,?,?,?,?,?,?)
                                  ON CONFLICT(repo,number) DO UPDATE SET revision=excluded.revision,
                                  version=excluded.version,processed=excluded.processed,retry_after=excluded.retry_after,
                                  complete=excluded.complete,record=excluded.record,source_bytes=excluded.source_bytes""",
                               (repo, raw[1], rev, VERSION, stamp, retry_at, int(successful), payload,
                                len((raw[5] + "\n" + raw[6]).encode())))
            processed += 1
        return {"processed": processed, "cached": skipped, "evidence_retry": errors,
                "partial": partial, "endpoint_failures": reader.failures,
                "endpoint_deferred": reader.deferred, "diagnostics": reader.diagnostics}
    finally:
        db.close()


def retrieve(index, request, repos):
    db = connect(index)
    ranked = []
    try:
        query = query_text(request, index.settings)
        cutoff = (datetime.now(timezone.utc) - timedelta(days=30)).isoformat(timespec="seconds")
        for repo in repos:
            rows = db.execute("""SELECT h.repo,h.number,h.kind,h.state,h.updated,h.title,h.body,
                                        d.revision,d.version,d.record,d.processed
                                 FROM history h LEFT JOIN distilled_history d
                                   ON h.repo=d.repo AND h.number=d.number WHERE h.repo=?""", (repo,))
            for row in rows:
                raw = row[:7]
                if row[7] == revision(raw) and row[8] == VERSION and row[10] > cutoff:
                    record = json.loads(row[9])
                else:
                    record = metadata(raw, index.settings)
                    record["evidence_complete_for_bounded_sample"] = False
                # Score each extracted claim independently so unrelated notes cannot
                # dilute a precise symptom, cause, solution or verification match.
                fields = ("reported_problem", "reported_root_cause", "reported_solution",
                          "reported_verification", "reported_failure", "technical_notes",
                          "affected_paths", "review_findings_unverified", "discussion_notes_unverified")
                searchable = [record["title"]]
                for field in fields:
                    searchable.extend(record.get(field, []))
                score = max((similarity(text, value)
                             for value in searchable
                             for text in (request.problem_summary, query)), default=0.0)
                if score < (0.55 if record["classification"] != "technical" else 0.25):
                    continue
                if record["status"] == "merged_not_production_verified":
                    score += 0.04
                ranked.append({"source": "distilled_github_history", "similarity": round(min(score, 1), 3), **record})
        return sorted(ranked, key=lambda r: (r["similarity"], r["source_updated"]), reverse=True)[:8]
    finally:
        db.close()


def _serialized_size(value):
    return len(json.dumps(value, ensure_ascii=True).encode())


def evidence_identity(record):
    identity = (str(record.get("repo", "")).casefold(), record.get("number") or record.get("pr"))
    reference = record.get("url") or record.get("reference")
    refmatch = re.fullmatch(r"https://github\.com/([^/]+/[^/]+)/(?:pull|issues)/(\d+)", str(reference or ""))
    if refmatch:
        identity = (refmatch[1].casefold(), int(refmatch[2]))
    if not identity[0] or not identity[1]:
        identity = ("text", " ".join(sorted(terms(str(record.get("problem") or record.get("title") or "")))),
                    record.get("outcome") or record.get("status"))
    return identity


def budget_evidence(records, settings, *, max_bytes=MAX_CONTEXT_BYTES):
    """Single cap across local, historical and shared advisory sources."""
    # Resolve duplicate identities before applying relevance ranking or byte limits.
    # A metadata match must never replace a recorded repair/deployment outcome.
    groups = {}
    for item in records:
        identity = evidence_identity(item)
        groups.setdefault(identity, []).append(item)
    ordered = []
    priority = {"local_doctor_archive": 2, "shared_doctor_advisory": 1}
    for group in groups.values():
        winner = max(group, key=lambda item: (
            priority.get(item.get("source"), 0),
            item.get("updated", ""),
            float(item.get("similarity", 0))))
        record = dict(winner)
        record["similarity"] = max(float(item.get("similarity", 0)) for item in group)
        ordered.append(record)
    ordered.sort(key=lambda item: item["similarity"], reverse=True)
    out = []
    for original in ordered:
        record = dict(original)
        for field in ("patch_excerpts", "comments", "review_notes"):
            record.pop(field, None)
        for key in ("problem", "title", "reason", "summary"):
            if key in record:
                record[key] = " ".join(compact_lines(record[key], settings, limit=2))[:400]
        if isinstance(record.get("lessons"), list):
            lines = []
            for item in record["lessons"]:
                lines.extend(compact_lines(item.get("detail", "") if isinstance(item, dict) else item,
                                           settings, technical=True, limit=2))
            record["lessons"] = list(dict.fromkeys(lines))[:2]
        for field in ("discussion_notes_unverified", "review_findings_unverified", "technical_notes",
                      "lessons", "affected_paths", "observed_merge_checks", "reported_verification",
                      "reported_solution", "reported_root_cause", "reported_problem", "reported_failure"):
            if _serialized_size(record) <= MAX_RECORD_BYTES:
                break
            record.pop(field, None)
        if _serialized_size(record) > MAX_RECORD_BYTES:
            continue
        if len(out) >= 5:
            break
        if _serialized_size([*out, record]) > max_bytes:
            continue
        out.append(record)
    return out


def coverage(index, repos):
    db = connect(index)
    try:
        result = []
        for repo in repos:
            total = current = source_bytes = distilled_bytes = stale = partial = 0
            counts = {}
            for row in db.execute("""SELECT h.repo,h.number,h.kind,h.state,h.updated,h.title,h.body,
                                           d.revision,d.version,d.record,d.source_bytes,d.complete
                                    FROM history h LEFT JOIN distilled_history d
                                      ON h.repo=d.repo AND h.number=d.number WHERE h.repo=?""", (repo,)):
                total += 1
                if row[7] != revision(row[:7]) or row[8] != VERSION:
                    stale += int(row[7] is not None)
                    continue
                if not row[11]:
                    partial += 1
                current += 1
                source_bytes += row[10]
                distilled_bytes += len(row[9].encode())
                classification = json.loads(row[9])["classification"]
                counts[classification] = counts.get(classification, 0) + 1
            result.append({"repo": repo, "indexed": total, "distilled_current": current,
                           "pending_or_retry": total-current+partial, "pending_distillation": total-current,
                           "partial_evidence": partial, "stale_revision": stale,
                           "classification": counts, "source_metadata_bytes": source_bytes,
                           "stored_knowledge_bytes": distilled_bytes})
        return result
    finally:
        db.close()
